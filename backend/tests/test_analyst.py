"""Ask the facility (SPEC §9 ⑧): the read-only guard, chart choice and Analyst reply parsing (no Snowflake)."""

import pytest
import yaml

from app.deep import analyst


def test_read_only_guard() -> None:
    sql = "WITH x AS (SELECT 1 AS a)\nSELECT a FROM x -- Generated by Cortex Analyst\n;"
    assert analyst.check_read_only(sql) == "WITH x AS (SELECT 1 AS a)\nSELECT a FROM x"
    assert analyst.check_read_only("SELECT 'drop table' AS t") == "SELECT 'drop table' AS t"  # inside a string
    for bad in ("DELETE FROM CORE.EVENTS", "SELECT 1; DROP TABLE CORE.EVENTS", "CALL SYSTEM$X()",
                "WITH a AS (SELECT 1) INSERT INTO t SELECT * FROM a"):  # fmt: skip
        with pytest.raises(ValueError):
            analyst.check_read_only(bad)


def test_comments_inside_quotes_are_kept() -> None:
    sql = "SELECT * FROM t WHERE note_text LIKE '%--%' AND x = 'it''s' -- Generated by Cortex Analyst\n;"
    assert analyst.check_read_only(sql) == "SELECT * FROM t WHERE note_text LIKE '%--%' AND x = 'it''s'"
    assert analyst.check_read_only('/* note */ SELECT "a--b" FROM t') == 'SELECT "a--b" FROM t'


def col(name: str, t: str) -> dict:
    return {"name": name, "type": t}


def test_chart_for_the_verified_questions() -> None:
    by_tier = analyst.chart_for([col("UNIT", "text"), col("TIER", "text"), col("ALERTS", "fixed")],
                                [["East", "HIGH", 2], ["Memory Care", "CRITICAL", 4], ["Memory Care", "HIGH", 3],
                                 ["West", "CRITICAL", 8], ["West", "HIGH", 1]])  # fmt: skip
    assert by_tier == {"type": "bar", "x": "UNIT", "y": "ALERTS", "series": "TIER"}
    hr = analyst.chart_for([col("NIGHT_OF", "date"), col("AVG_NIGHT_HEART_RATE", "real")], [["2026-10-16", 62.1]])
    assert hr == {"type": "line", "x": "NIGHT_OF", "y": "AVG_NIGHT_HEART_RATE"}
    exits = analyst.chart_for([col("RESIDENT_NAME", "text"), col("ROOM", "text"), col("UNIT", "text"),
                               col("BED_EXITS", "fixed")], [[f"R{i}", f"{200 + i}", "West", 5] for i in range(5)])  # fmt: skip
    assert exits == {"type": "bar", "x": "RESIDENT_NAME", "y": "BED_EXITS"}
    assert analyst.chart_for([col("N", "fixed")], [[3]]) is None
    assert analyst.chart_for([col("A", "text"), col("B", "fixed")], []) is None


def test_parse_message() -> None:
    body = {"message": {"content": [
        {"type": "text", "text": "This is our interpretation of your question:\n\nAlerts by unit"},
        {"type": "sql", "statement": "SELECT 1", "confidence": {"verified_query_used": {
            "name": "alerts_by_unit_tier_week", "question": "Alerts by unit and tier this week.", "verified_by": "Vigil"}}},
    ]}, "warnings": [{"message": "w"}]}  # fmt: skip
    out = analyst.parse_message(body)
    assert out["sql"] == "SELECT 1" and out["verified_query"]["name"] == "alerts_by_unit_tier_week"
    assert out["interpretation"].endswith("Alerts by unit") and out["warnings"] == ["w"]
    sugg = analyst.parse_message({"message": {"content": [{"type": "suggestions", "suggestions": ["a", "b"]}]}})
    assert sugg["sql"] is None and sugg["suggestions"] == ["a", "b"]


def test_semantic_model_has_the_five_verified_questions() -> None:
    model = yaml.safe_load(analyst.SEMANTIC_YAML.read_text())
    questions = [q["question"] for q in model["verified_queries"]]
    assert questions == analyst.SUGGESTED
    tables = {t["name"] for t in model["tables"]}
    assert {"residents", "vitals_15m", "events", "checks", "alerts", "nurse_notes"} <= tables
    for q in model["verified_queries"]:
        assert q["sql"].lstrip().upper().startswith(("SELECT", "WITH")) and "__" in q["sql"]
