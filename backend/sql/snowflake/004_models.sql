-- 004_models.sql: the five multi-series SNOWFLAKE.ML.ANOMALY_DETECTION models (SPEC §9 ②).
-- Run by `make train` (scripts/train_models.py), which first writes the training window into
-- ML.TRAINING_WINDOW: up to ANOMALY_TRAIN_DAYS days ending where last night's holdout starts, so the
-- replayed night is always out-of-sample. Idempotent: CREATE OR REPLACE retrains from the current window.
--
-- One series per resident (SERIES_COLNAME = RESIDENT_ID), 15-minute buckets, unsupervised
-- (LABEL_COLNAME = ''). Every column besides series, timestamp and target is an exogenous feature:
-- IN_BED_FRAC lets the model expect a lower heart rate and less movement while the resident is in bed.

CREATE TABLE IF NOT EXISTS ML.TRAINING_WINDOW (
    NAME       VARCHAR NOT NULL PRIMARY KEY,
    TRAIN_FROM TIMESTAMP_NTZ NOT NULL,
    TRAIN_TO   TIMESTAMP_NTZ NOT NULL,  -- exclusive
    UPDATED_AT TIMESTAMP_NTZ
);

CREATE OR REPLACE VIEW ML.AD_TRAIN_HR AS
SELECT v.RESIDENT_ID, v.BUCKET_TS, v.HR_AVG, v.IN_BED_FRAC
FROM CORE.VITALS_15M v JOIN ML.TRAINING_WINDOW w ON w.NAME = 'anomaly'
WHERE v.BUCKET_TS >= w.TRAIN_FROM AND v.BUCKET_TS < w.TRAIN_TO AND v.HR_AVG IS NOT NULL AND v.IN_BED_FRAC IS NOT NULL;

CREATE OR REPLACE VIEW ML.AD_TRAIN_RR AS
SELECT v.RESIDENT_ID, v.BUCKET_TS, v.RR_AVG, v.IN_BED_FRAC
FROM CORE.VITALS_15M v JOIN ML.TRAINING_WINDOW w ON w.NAME = 'anomaly'
WHERE v.BUCKET_TS >= w.TRAIN_FROM AND v.BUCKET_TS < w.TRAIN_TO AND v.RR_AVG IS NOT NULL AND v.IN_BED_FRAC IS NOT NULL;

CREATE OR REPLACE VIEW ML.AD_TRAIN_SPO2 AS
SELECT v.RESIDENT_ID, v.BUCKET_TS, v.SPO2_MIN, v.IN_BED_FRAC
FROM CORE.VITALS_15M v JOIN ML.TRAINING_WINDOW w ON w.NAME = 'anomaly'
WHERE v.BUCKET_TS >= w.TRAIN_FROM AND v.BUCKET_TS < w.TRAIN_TO AND v.SPO2_MIN IS NOT NULL AND v.IN_BED_FRAC IS NOT NULL;

CREATE OR REPLACE VIEW ML.AD_TRAIN_SKIN_TEMP AS
SELECT v.RESIDENT_ID, v.BUCKET_TS, v.SKIN_TEMP_AVG, v.IN_BED_FRAC
FROM CORE.VITALS_15M v JOIN ML.TRAINING_WINDOW w ON w.NAME = 'anomaly'
WHERE v.BUCKET_TS >= w.TRAIN_FROM AND v.BUCKET_TS < w.TRAIN_TO AND v.SKIN_TEMP_AVG IS NOT NULL
  AND v.IN_BED_FRAC IS NOT NULL;

CREATE OR REPLACE VIEW ML.AD_TRAIN_MOTION AS
SELECT v.RESIDENT_ID, v.BUCKET_TS, v.MOTION_SUM, v.IN_BED_FRAC
FROM CORE.VITALS_15M v JOIN ML.TRAINING_WINDOW w ON w.NAME = 'anomaly'
WHERE v.BUCKET_TS >= w.TRAIN_FROM AND v.BUCKET_TS < w.TRAIN_TO AND v.MOTION_SUM IS NOT NULL
  AND v.IN_BED_FRAC IS NOT NULL;

CREATE OR REPLACE SNOWFLAKE.ML.ANOMALY_DETECTION ML.AD_HR(
    INPUT_DATA => TABLE(ML.AD_TRAIN_HR),
    SERIES_COLNAME => 'RESIDENT_ID', TIMESTAMP_COLNAME => 'BUCKET_TS', TARGET_COLNAME => 'HR_AVG',
    LABEL_COLNAME => '');

CREATE OR REPLACE SNOWFLAKE.ML.ANOMALY_DETECTION ML.AD_RR(
    INPUT_DATA => TABLE(ML.AD_TRAIN_RR),
    SERIES_COLNAME => 'RESIDENT_ID', TIMESTAMP_COLNAME => 'BUCKET_TS', TARGET_COLNAME => 'RR_AVG',
    LABEL_COLNAME => '');

CREATE OR REPLACE SNOWFLAKE.ML.ANOMALY_DETECTION ML.AD_SPO2(
    INPUT_DATA => TABLE(ML.AD_TRAIN_SPO2),
    SERIES_COLNAME => 'RESIDENT_ID', TIMESTAMP_COLNAME => 'BUCKET_TS', TARGET_COLNAME => 'SPO2_MIN',
    LABEL_COLNAME => '');

CREATE OR REPLACE SNOWFLAKE.ML.ANOMALY_DETECTION ML.AD_SKIN_TEMP(
    INPUT_DATA => TABLE(ML.AD_TRAIN_SKIN_TEMP),
    SERIES_COLNAME => 'RESIDENT_ID', TIMESTAMP_COLNAME => 'BUCKET_TS', TARGET_COLNAME => 'SKIN_TEMP_AVG',
    LABEL_COLNAME => '');

CREATE OR REPLACE SNOWFLAKE.ML.ANOMALY_DETECTION ML.AD_MOTION(
    INPUT_DATA => TABLE(ML.AD_TRAIN_MOTION),
    SERIES_COLNAME => 'RESIDENT_ID', TIMESTAMP_COLNAME => 'BUCKET_TS', TARGET_COLNAME => 'MOTION_SUM',
    LABEL_COLNAME => '');
